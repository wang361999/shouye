// ============ Button ============
type ButtonProps = {
  children: ReactNode;
  variant?: "primary" | "secondary" | "danger" | "ghost";
  size?: "sm" | "md";
  onClick?: () => void;
  disabled?: boolean;
  loading?: boolean;
  type?: "button" | "submit";
  className?: string;
};

export function Button({ children, variant = "primary", size = "md", onClick, disabled, loading, type = "button", className = "" }: ButtonProps) {
  const base = variant === "primary" ? "admin-btn-primary" : variant === "secondary" ? "admin-btn-secondary" : variant === "danger" ? "admin-btn-danger" : "admin-btn-ghost";
  const sz = size === "sm" ? "px-3 py-1.5 text-xs" : "";
  return (
    <button type={type} onClick={onClick} disabled={disabled || loading} className={`${base} ${sz} ${className}`}>
      {loading && <Spinner className="w-3 h-3" />}
      {children}
    </button>
  );
}

